#!/usr/bin/env python3
"""Generates docs/API.md from the route registrations (method, path, owner file, role rule)."""
import re, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
owners = {"saksham_api.cpp": "Saksham", "nikita_api.cpp": "Nikita", "vansh_api.cpp": "Vansh", "krishna_api.cpp": "Krishna", "ankit_api.cpp": "Ankit", "shaurya_api.cpp": "Shaurya"}
rows = []
for f, owner in owners.items():
    text = (root / "backend" / f).read_text()
    starts = [m for m in re.finditer(r'r\.(get|post|put|del)\("([^"]+)"', text)]
    for i, m in enumerate(starts):
        seg = text[m.start(): starts[i + 1].start() if i + 1 < len(starts) else len(text)]
        rr = re.search(r'require\(sys, req, \{([^}]*)\}\)', seg)
        if rr: access = ", ".join(x.strip().strip('"') for x in rr.group(1).split(","))
        elif "requireAny(sys, req)" in seg or "authenticate(sys, req)" in seg: access = "Any logged-in user (own data only for Patients where applicable)"
        else: access = "Public"
        rows.append((m.group(2), {"get": "GET", "post": "POST", "put": "PUT", "del": "DELETE"}[m.group(1)], access, owner))
out = ["# REST API reference", "", "Generated by `scripts/gen_api_docs.py` from the route registrations. All routes except those marked Public require `Authorization: Bearer <token>` (from `POST /api/auth/login`). Errors are JSON: `{\"error\": \"...\"}`.", "",
       f"Total routes: **{len(rows)}**", "", "| Method | Path | Allowed roles | Owner |", "|---|---|---|---|"]
for path, method, access, owner in rows: out.append(f"| {method} | `{path}` | {access} | {owner} |")
out += ["", "## Conventions", "- List endpoints accept `limit`/`offset` (or `page`/`limit` for `/api/medicines`) and return `{items, total}`.",
        "- Status codes: 400 malformed request, 401 not authenticated, 403 role not permitted, 404 not found, 409 conflict/business rule, 422 validation failure, 429 login throttled.",
        "- Patients may only read and act on their own records; self-service requests always enter the queue as `Normal` until staff triage.",
        "- Substitute medicines are suggestions; only a user with the Pharmacist role can approve one."]
(root / "docs/API.md").write_text("\n".join(out) + "\n"); print(len(rows), "routes documented")
